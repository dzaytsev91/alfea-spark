import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const books={ps:'Философский камень',cs:'Тайная комната',pa:'Узник Азкабана',gf:'Кубок огня',op:'Орден Феникса',hbp:'Принц-полукровка',dh:'Дары Смерти'};
const rows=name=>readFileSync(root+`data/harry-potter/${name}.tsv`,'utf8').trim().split('\n').map(line=>line.split('\t').map(x=>x.trim()));
const chapterSource=(book,chapter)=>`https://www.hp-lexicon.org/source/the-harry-potter-novels/${book}/${book}${chapter}/`;
// Fixed ranges preserve shared results. Append within a range; never reorder published rows.
const bank=[];
function add(id,tag,kind,topic,q,options,why,source,points=3){
  // Canonical option order is deterministic and stable; the UI shuffles it again.
  const offset=id%4;
  const ordered=[...options.slice(offset),...options.slice(0,offset)];
  bank.push({id,tag,kind,topic,icon:{story:'📖',spell:'🪄',creature:'🐾',film:'🎬',chapter:'📚'}[kind],points,q,options:ordered,answer:(4-offset)%4,why,source});
}
// Distractors are selected once at build time, never when decoding a shared result.
function optionsFrom(correct,pool,seed){
  const candidates=[...new Set(pool)].filter(x=>x!==correct);
  const wrong=[];
  while(wrong.length<3){seed=(Math.imul(seed,1664525)+1013904223)>>>0;wrong.push(...candidates.splice(seed%candidates.length,1));}
  return [correct,...wrong];
}
Object.entries(books).forEach(([book,title],bookIndex)=>{
  rows(book).forEach(([chapter,q,answer,wrong],i)=>{
    const id=100+bookIndex*100+i;
    const choices=[answer,...wrong.split(';')];
    add(id,`Книга · ${title}`,'story',`${book}:${chapter}`,q,choices,`${answer}. «${title}», глава ${chapter}.`,chapterSource(book,chapter),3);
  });
});
const spells=rows('spells');
spells.forEach(([slug,name,effect],i)=>{
  const id=850+i;
  add(id,'Заклинания','spell',`spell:${name}`,`Какая формула ${effect}?`,optionsFrom(name,spells.map(r=>r[1]),id),`${name} — ${effect}.`,`https://www.hp-lexicon.org/magic/${slug}/`,4);
});
const creatures=rows('creatures');
creatures.forEach(([slug,name,trait],i)=>{
  const id=950+i;
  add(id,'Бестиарий','creature',`creature:${slug}`,`Какое волшебное существо ${trait}?`,optionsFrom(name,creatures.map(r=>r[1]),id),`${name}: ${trait}.`,`https://harrypotter.fandom.com/wiki/${slug}`,4);
});
const films=rows('films');
films.forEach(([role,actor,slug,gender],i)=>{
  const id=1050+i;
  add(id,'Кино · актёры','film',`actor:${slug}`,`Кому досталась роль ${role} в экранизациях?`,optionsFrom(actor,films.filter(r=>r[3]===gender).map(r=>r[1]),id),`Эту роль играет ${actor}.`,`https://en.wikipedia.org/wiki/${slug}`);
});
rows('chapters').forEach(([book,chapter,title],i)=>{
  const id=1100+i;
  add(id,'Книги · главы','chapter',`${book}:${chapter}`,`В какой книге есть глава «${title}»?`,optionsFrom(books[book],Object.values(books),id),`«${title}» — глава ${chapter} книги «${books[book]}».`,chapterSource(book,chapter),4);
});
const ids=new Set(),texts=new Set();
for(const q of bank){
  if(ids.has(q.id)||texts.has(q.q))throw Error(`Duplicate question ${q.id}: ${q.q}`);
  if(q.options.length!==4||new Set(q.options).size!==4||q.options.some(x=>!x))throw Error(`Invalid options ${q.id}`);
  if(/[<>]|\[MASKED|undefined/.test(JSON.stringify(q)))throw Error(`Invalid content ${q.id}`);
  if(!/^https:\/\//.test(q.source))throw Error(`Invalid source ${q.id}`);
  ids.add(q.id);texts.add(q.q);
}
writeFileSync(root+'harry-potter-expanded.js',`// Generated by node scripts/build-harry-potter.mjs. Edit data/harry-potter/*.tsv.\n'use strict';\nconst expandedQuestions=${JSON.stringify(bank,null,2)};\n`);
console.log(`Built ${bank.length} new questions; total with legacy bank: ${bank.length+100}.`);
